#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
require('../core.js');
require('../vyvoj.js');
globalThis.window = globalThis;
require('../motyli-podnoz-mesh.js');
require('../motyli-podnoz.js');
const V = globalThis.Vyvoj;
assert(V.MODELS.some((m) => m.id === 'MOT'), 'MOT je v katalogu Umělecké');
const cfg = V.normalize({ model: 'MOT' });
assert.equal(cfg.model, 'MOT');
const A = V.analyze(cfg);
assert.equal(A.capacity, null, 'nosnost se netvrdí');
assert.equal(A.cost, null, 'cena se netvrdí');
assert.equal(A.build.parts.length, 33, 'STEP má 33 vykreslených těles');
assert(A.build.parts.every((p) => p.solid.verts.length && p.solid.faces.length));
assert.equal(A.build.parts.reduce((n, p) => n + p.solid.faces.length, 0), 125608, 'náhled používá síť z aktualizovaného STEP');
const xyz = A.build.parts.flatMap((p) => p.solid.verts);
const bounds = [0, 1, 2].map((axis) => [Math.min(...xyz.map((v) => v[axis])), Math.max(...xyz.map((v) => v[axis]))]);
assert(Math.abs(bounds[0][1] - bounds[0][0] - A.build.dims.Lf) < 2);
assert(Math.abs(bounds[1][1] - bounds[1][0] - A.build.dims.Wf) < 2);
assert(Math.abs(bounds[2][1] - bounds[2][0] - A.build.dims.Hf) < 2, 'nominální náhled odpovídá výšce podnože');
assert.deepEqual(A.build.dims, { Lf: 1533, Wf: 842, Hf: 732 });
const resized = V.normalize({ model: 'MOT', L: 1600, H: 780 });
assert.equal(resized.L, 1600, 'délka MOT přijímá změněnou hodnotu');
assert.equal(resized.H, 780, 'výška MOT přijímá změněnou hodnotu');
assert(resized.W > cfg.W, 'hloubka MOT se odvozuje od změny délky');
const resizedBuild = V.build(resized);
assert.notDeepEqual(resizedBuild.parts[2].solid.verts, A.build.parts[2].solid.verts, 'změna rozměrů přepočítá geometrii jeklu');
const lengthOnly = V.build(V.normalize({ model: 'MOT', L: 1600, H: cfg.H }));
const lengthPoints = lengthOnly.parts.flatMap((p) => p.solid.verts);
const lengthSpan = (axis) => Math.max(...lengthPoints.map((p) => p[axis])) - Math.min(...lengthPoints.map((p) => p[axis]));
assert(lengthSpan(0) > bounds[0][1] - bounds[0][0] + 60, 'změna délky rozšiřuje podnož v půdorysu');
assert(Math.abs(lengthSpan(2) - (bounds[2][1] - bounds[2][0])) < 2, 'samotná změna délky nezvedá podnož');
const sectionSpan = (solid) => Math.hypot(...solid.verts[397].map((x, i) => x - solid.verts[531][i]));
assert(Math.abs(sectionSpan(resizedBuild.parts[2].solid) - sectionSpan(A.build.parts[2].solid)) < 1e-4, 'příčný rozměr jeklu se při změně délky zachová');
const clamped = V.normalize({ model: 'MOT', L: 1200, W: 700, H: 900 });
assert.equal(clamped.L, 1400, 'délka MOT se omezí na minimum');
assert.equal(clamped.H, 800, 'výška MOT se omezí na maximum');
assert.equal(V.MOTYLI_LIMITS.L.max, 1600, 'maximální délka MOT odpovídá zadání');
assert.equal(V.normalize({ model: 'PZ' }).model, 'PZ', 'ostatní modely zůstávají dostupné');
assert.match(fs.readFileSync(require.resolve('../vyvoj.html'), 'utf8'), /motyli-podnoz-mesh\.js[\s\S]*motyli-podnoz\.js/);
assert.match(fs.readFileSync(require.resolve('../vyvoj.html'), 'utf8'), /function renderMotyli\(\)/);
assert.match(fs.readFileSync(require.resolve('../vyvoj.html'), 'utf8'), /range\.disabled\s*=\s*num\.disabled\s*=\s*false/);
console.log('OK kontrola MOT: katalog, aktualizovaný náhled 33 těles, rozměry a neověřené výstupy');
